"""Generate the experimental tables from the scored curves."""

import argparse
import json
import os
from pathlib import Path

import numpy as np

from compare import UNSW_CAL, read


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results",type=Path)
    root=parser.parse_args().results.resolve()
    source=Path(__file__).resolve().parents[3]/"manuscript"
    report=json.loads((root/"summary.json").read_text(encoding="utf-8"))
    items=report["comparisons"]
    fit=report["calibration"]
    figure_folder=Path(os.path.relpath(root/"figures",source)).as_posix()
    nasa_c=items["nasa-c"]
    nasa_d=items["nasa-d"]
    unsw_high=items["Data_10Hz_15Nm_H"]
    low_load=read(root/"curves"/"nasa-b.csv")
    unloaded=(low_load["roll_deg"]>=19.5)&(low_load["roll_deg"]<=21.5)
    high_dte=read(root/"curves"/"Data_10Hz_15Nm_H.csv")
    def second_harmonic(field):
        return 2*abs(np.fft.rfft(high_dte[field])[2])/len(high_dte)
    macros={
        "GearExperimentPath":rf"\detokenize{{{figure_folder}/}}",
        "NasaK":f"{fit['nasa']['stiffness_N_m']/1e6:.0f}",
        "NasaZeta":f"{fit['nasa']['damping_ratio']:.2f}",
        "UnswK":f"{fit['unsw']['stiffness_N_m']/1e6:.0f}",
        "UnswZeta":f"{fit['unsw']['damping_ratio']:.2f}",
        "UnswShift":f"{fit['unsw']['phase_shift_bins']/128:.3f}",
        "NasaStepDelta":f"{nasa_d['brep_fine_step']['delta_to_nominal_cad_rms']:.2f}",
        "UnswStepDelta":f"{unsw_high['brep_fine_step']['delta_to_nominal_cad_rms']:.3f}",
        "NasaInertiaSensitivity":f"{nasa_c['nasa_inertia_times10']['delta_to_nominal_cad_rms']:.1f}",
        "NasaInertiaRMSE":f"{nasa_c['nasa_inertia_times10']['error']['rms']:.1f}",
        "NasaLowLoadFloor":f"{np.min(low_load['brep'][unloaded]):.0f}",
        "UnswMeasuredSecond":f"{second_harmonic('measured'):.2f}",
        "UnswNativeSecond":f"{second_harmonic('brep'):.2f}",
    }
    lines=[r"% Generated by benchmarks/gears/experimental/paper_section.py."]
    lines.extend(rf"\newcommand{{\{name}}}{{{value}}}" for name,value in macros.items())
    lines.append(r"\newcommand{\NasaExperimentRows}{%")
    for panel in "abcd":
        row=items[f"nasa-{panel}"]
        cad=row["brep"]["error"]
        mesh=row["mesh"]["error"]
        lines.append(f"7({panel}) & {row['rpm']:.0f} & {row['input_torque_Nm']:.2f} & "
                     f"{cad['test_peak']:.0f} & {cad['rms']:.1f} & {mesh['rms']:.1f} & "
                     rf"{'Fit' if panel=='a' else 'Held out'} \\")
    lines.append("}")
    lines.append(r"\newcommand{\UnswExperimentRows}{%")
    for key in (UNSW_CAL,"Data_05Hz_05Nm_H","Data_10Hz_15Nm_H"):
        row=items[key]
        cad=row["brep"]["error"]
        mesh=row["mesh"]["error"]
        lines.append(f"{row['rpm']:.1f} & {row['input_torque_Nm']:.2f} & {cad['data_rms']:.2f} & "
                     f"{cad['rms']:.2f} & {mesh['rms']:.2f} & "
                     rf"{'Fit' if key==UNSW_CAL else 'Held out'} \\")
    lines.append("}")
    (source/"gears-experiment-results.tex").write_text("\n".join(lines)+"\n",encoding="utf-8")


if __name__=="__main__":
    main()
