"""Populate and compile the industrial STEP benchmark supplement."""

import argparse
import json
import os
import shutil
import subprocess
from pathlib import Path

from run import CASES


NAMES=("Spur 24/48","Helical 25/45","NASA geometry 28/28","Two-stage 4:1")


def panel(key):
    return r"\newcommand{\%s}{%%" % key


def scientific(value):
    coefficient,exponent=f"{value:.2e}".split("e")
    return rf"\ensuremath{{{coefficient}\times10^{{{int(exponent)}}}}}"


def dynamic_rows(gear):
    rows=[]
    for case,name in zip(CASES,NAMES,strict=True):
        g=gear["comparison"][case]
        row=(
            f"{name} & {g['cad_s']:.3f} & {g['fine_mesh_s']:.3f} & {g['fine_mesh_speed_ratio']:.2f} & "
            f"{g['mesh_geometry_rms_um']:.3f} & {g['mesh_force_rms_pct']:.1f} & "
            rf"{g['cad_nominal_step_rms_um']:.3f} \\"
        )
        rows.append(row)
    return rows


def axial_rows(gear):
    rows=[]
    for case in ("helical","reducer"):
        record=gear["dense_axial"][case]
        for stage,(difference,reference) in enumerate(zip(record["matched_geometry"],record["cad_31_vs_63"],
                                                           strict=True),start=1):
            name=("Helical" if case=="helical" else f"Reducer stage {stage}")
            speed=f"{record['speed_ratio']:.2f}" if stage==1 else ""
            values=(difference["transmission_rms_um"],reference["transmission_rms_um"],
                    difference["normal_force_rms_pct"],reference["normal_force_rms_pct"])
            rows.append(f"{name} & {speed} & {values[0]:.3f} & {values[1]:.3f} & "
                        rf"{values[2]:.1f} & {values[3]:.1f} \\")
    return rows


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results",type=Path)
    args=parser.parse_args()
    root=args.results.resolve()
    gear=json.loads((root/"summary.json").read_text(encoding="utf-8"))
    bearing=json.loads((root/"bearing"/"summary.json").read_text(encoding="utf-8"))
    cad=bearing["cad"]
    mesh=bearing["mesh-fine"]
    duty=gear["runs"]["reducer-cad-duty"]
    duty_mesh=gear["runs"]["reducer-mesh-duty"]
    section=gear["section_ablation"]
    macros={
        "SectionGain":f"{section['speed_ratio']:.2f}",
        "SectionDrift":scientific(section["transmission_max_um"]),
        "DutyCad":f"{duty['median_integration_s']:.2f}",
        "DutyMesh":f"{duty_mesh['median_integration_s']:.2f}",
        "DutyGain":f"{duty_mesh['median_integration_s']/duty['median_integration_s']:.2f}",
        "DutyGap":f"{min(row['native_minimum_sample_um'] for row in duty['stage']):.2f}",
        "DutyAxial":f"{duty['stage'][1]['peak_axial_N']:.0f}",
        "BearingCad":f"{cad['median_s']:.3f}",
        "BearingMesh":f"{mesh['median_s']:.3f}",
        "BearingGain":f"{mesh['speed_ratio']:.2f}",
        "BearingDrift":f"{mesh['relative_to_matched_cad']['orbit_rms_um']:.3f}",
        "BearingMax":f"{mesh['relative_to_matched_cad']['orbit_max_um']:.2f}",
        "BearingPeak":f"{mesh['relative_to_matched_cad']['peak_roller_rms_N']:.1f}",
        "BearingGuard":f"{min(cad['min_native_interval_radial_gap_um'],mesh['min_native_interval_radial_gap_um']):.2f}",
    }
    project=Path(__file__).resolve().parents[2]
    source=project/"manuscript"
    paths=[]
    for folder in (root/"figures",root/"bearing"/"figures"):
        try:
            folder=Path(os.path.relpath(folder,source))
        except ValueError:
            pass
        paths.append(rf"{{\detokenize{{{folder.as_posix()}/}}}}")
    suffix=r"\graphicspath{"+"".join(paths)+"}"
    lines=["% Generated by benchmarks/gears/paper.py.",suffix]
    lines.extend(rf"\newcommand{{\{key}}}{{{value}}}" for key,value in macros.items())
    lines.extend([panel("MainRows"),*dynamic_rows(gear),"}"])
    lines.extend([panel("DenseRows"),*axial_rows(gear),"}"])
    (source/"industrial-results.tex").write_text("\n".join(lines)+"\n",encoding="utf-8")
    build=project/"build"/"industrial-paper"
    build.mkdir(parents=True,exist_ok=True)
    subprocess.run(["latexmk","-pdf","-interaction=nonstopmode","-halt-on-error","-file-line-error",
                    f"-outdir={build.as_posix()}","industrial.tex"],cwd=source,check=True)
    output=root/"paper"/"industrial.pdf"
    output.parent.mkdir(exist_ok=True)
    shutil.copyfile(build/"industrial.pdf",output)
    print(output)


if __name__=="__main__":
    main()
